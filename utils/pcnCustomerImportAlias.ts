import type { CustomerRef } from '../types.ts';

export const PCN_ALIAS_KEEP_SOURCE_KEY = 'KEEP_SOURCE_KEY' as const;
export const PCN_ALIAS_MAP_TO_TARGET = 'MAP_TO_TARGET' as const;

export type PcnCustomerAliasMode = typeof PCN_ALIAS_KEEP_SOURCE_KEY | typeof PCN_ALIAS_MAP_TO_TARGET;

export interface PcnCustomerAliasCandidate {
  sourceKey: string;
  targetKey: string;
}

export interface PcnCustomerAliasDecision {
  sourceKey: string;
  mode: PcnCustomerAliasMode;
  targetKey?: string;
}

function normalizeKey(value: unknown): string {
  return String(value || '').trim().toLowerCase();
}

function readDecision(value: unknown): PcnCustomerAliasDecision | null {
  if (!value || typeof value !== 'object' || Array.isArray(value)) return null;
  const record = value as Record<string, unknown>;
  const sourceKey = normalizeKey(record.sourceKey);
  const mode = String(record.mode || '').trim().toUpperCase();
  const targetKey = normalizeKey(record.targetKey);
  if (!sourceKey || (mode === PCN_ALIAS_MAP_TO_TARGET && !targetKey)) return null;
  if (mode !== PCN_ALIAS_KEEP_SOURCE_KEY && mode !== PCN_ALIAS_MAP_TO_TARGET) return null;
  return {
    sourceKey,
    mode: mode as PcnCustomerAliasMode,
    ...(targetKey ? { targetKey } : {}),
  };
}

/**
 * Validates alias choices against the exact candidate list generated by the
 * current preview. It intentionally does not infer a default mapping.
 */
export function validatePcnCustomerAliasDecisions(
  candidates: readonly PcnCustomerAliasCandidate[],
  decisions: unknown,
): PcnCustomerAliasDecision[] {
  if (!Array.isArray(decisions)) throw new Error('Mỗi ứng viên alias phải có một quyết định tường minh.');
  if (decisions.length !== candidates.length) throw new Error('Phải quyết định đầy đủ từng ứng viên alias trước khi apply.');

  const candidateBySource = new Map(candidates.map((candidate) => [normalizeKey(candidate.sourceKey), {
    sourceKey: normalizeKey(candidate.sourceKey),
    targetKey: normalizeKey(candidate.targetKey),
  }]));
  const parsed = decisions.map(readDecision);
  if (parsed.some((decision) => !decision)) throw new Error('Quyết định alias không hợp lệ.');
  const normalized = parsed as PcnCustomerAliasDecision[];
  const seen = new Set<string>();
  for (const decision of normalized) {
    const candidate = candidateBySource.get(decision.sourceKey);
    if (!candidate || seen.has(decision.sourceKey)) throw new Error('Quyết định alias không khớp candidate hiện tại.');
    seen.add(decision.sourceKey);
    if (decision.mode === PCN_ALIAS_KEEP_SOURCE_KEY && decision.targetKey) {
      throw new Error('Quyết định giữ khóa nguồn không được kèm khóa đích.');
    }
    if (decision.mode === PCN_ALIAS_MAP_TO_TARGET && decision.targetKey !== candidate.targetKey) {
      throw new Error('Khóa đích mapping alias không khớp candidate hiện tại.');
    }
  }
  if (seen.size !== candidateBySource.size) throw new Error('Phải quyết định đầy đủ từng ứng viên alias trước khi apply.');
  return normalized;
}

export function mapPcnCustomerAliasCustomer(
  source: CustomerRef,
  target: CustomerRef,
  decision: PcnCustomerAliasDecision,
): CustomerRef {
  if (decision.mode === PCN_ALIAS_KEEP_SOURCE_KEY) return source;
  return {
    ...source,
    // Keep the canonical target identity. If it has no customerCode, its name
    // remains the stable document id.
    name: target.name,
    customerCode: target.customerCode || '',
  };
}

